-- ---------- price helpers ---------------------------------------------------
-- ₹60 → Z60, ₹450 → D50, ₹1200 → A200
create or replace function public.price_to_code(p numeric) returns text
language sql immutable as $$
  select case
    when p is null or p < 1 or p > 9999 then null
    when p < 100  then 'Z' || lpad(round(p)::int::text, 2, '0')
    when p < 1000 then chr(64 + (round(p)::int / 100))  || lpad((round(p)::int % 100)::text, 2, '0')
    else               chr(64 + (round(p)::int / 1000)) || lpad((round(p)::int % 1000)::text, 3, '0')
  end
$$;

create or replace function public.code_to_price(c text) returns numeric
language sql immutable as $$
  select case
    when c is null or c !~ '^([A-K][0-9]{2,3}|Z[0-9]{2})$' then null
    when left(c, 1) = 'Z' then right(c, 2)::int
    when length(c) = 3   then (ascii(left(c, 1)) - 64) * 100  + right(c, 2)::int
    else                      (ascii(left(c, 1)) - 64) * 1000 + right(c, 3)::int
  end
$$;

-- Selling price hidden in the MRP decimals: 650.50 → 500, 1500.12 → 1200, no decimals → MRP.
create or replace function public.actual_from_mrp(mrp numeric) returns numeric
language sql immutable as $$
  select case
    when mrp is null or mrp <= 0 then null
    when mrp = trunc(mrp) then round(mrp)
    when mrp >= 1000 then (round((mrp - trunc(mrp)) * 100))::int * 100
    else (round((mrp - trunc(mrp)) * 100))::int * 10
  end
$$;

-- New random 6-digit barcode not used by any product.
create or replace function public.new_barcode() returns text
language plpgsql volatile set search_path = public as $$
declare b text;
begin
  loop
    b := (100000 + floor(random() * 900000))::int::text;
    exit when not exists (select 1 from products where item_code = b)
          and not exists (select 1 from product_barcodes where barcode_number = b);
  end loop;
  return b;
end $$;

