create or replace function public.wizard_add_item(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_cat    text := left(initcap(regexp_replace(trim(coalesce(p->>'category', '')), '\s+', ' ', 'g')), 40);
  v_style  text := left(initcap(regexp_replace(trim(coalesce(p->>'style', '')), '\s+', ' ', 'g')), 40);
  v_sleeve text := nullif(upper(regexp_replace(trim(coalesce(p->>'sleeve', '')), '\s+', ' ', 'g')), '');
  v_words  text; v_prefix text;
begin
  if not public.is_manager() then raise exception 'Not allowed'; end if;
  if v_cat = '' or v_style = '' then raise exception 'Category and style are required.'; end if;
  if v_sleeve is not null and v_sleeve not in ('F/S', 'H/S') then raise exception 'Sleeve must be F/S, H/S or empty.'; end if;
  v_words := case when position(upper(v_cat) in upper(v_style)) > 0 then v_style else v_style || ' ' || v_cat end;
  v_prefix := left(upper(regexp_replace(trim(coalesce(nullif(p->>'label_prefix', ''), v_words || ' ' || coalesce(v_sleeve, ''))), '\s+', ' ', 'g')), 60);
  if exists (select 1 from generic_items where label_prefix = v_prefix) then
    raise exception '''%'' already exists.', v_prefix;
  end if;
  insert into generic_items (category, style, sleeve, label_prefix, sort_order) values (v_cat, v_style, v_sleeve, v_prefix, 100);
  return jsonb_build_object('category', v_cat, 'style', v_style, 'sleeve', v_sleeve, 'label_prefix', v_prefix);
end $$;

