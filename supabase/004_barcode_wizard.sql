-- The main call. Finds the product for {prefix, size, code} exactly like the old tool
-- (generic items: same code; innerwear: any code), otherwise creates the product
-- "PREFIX SIZE CODE" with a new barcode. Updates its selling / purchase price and latest MRP.
-- p: {prefix, size, code, mrp, sale_price?, purchase_price?}
create or replace function public.wizard_barcode(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_prefix  text := upper(trim(coalesce(p->>'prefix', '')));
  v_size    text := upper(regexp_replace(trim(coalesce(p->>'size', '')), '\s+', '', 'g'));
  v_code    text := upper(regexp_replace(coalesce(p->>'code', ''), '\s+', '', 'g'));
  v_mrp     numeric := round((p->>'mrp')::numeric, 2);
  v_sale    numeric;
  v_cost    numeric := nullif(p->>'purchase_price', '')::numeric;
  v_generic boolean;
  v_pid     bigint;
  v_created boolean := false;
  v_name    text;
  pr        record;
begin
  if not public.is_manager() then raise exception 'Only Admin / Co-admin can make barcodes'; end if;
  if v_prefix = '' or v_size = '' then raise exception 'Product and size are required.'; end if;
  if v_mrp is null or v_mrp <= 0 or v_mrp > 99999 then raise exception 'MRP must be between ₹0.01 and ₹99,999.'; end if;
  if v_code !~ '^([A-K][0-9]{2,3}|Z[0-9]{2})$' then raise exception 'Code must look like D50, A200 or Z60.'; end if;
  v_sale := coalesce(nullif(p->>'sale_price', '')::numeric, code_to_price(v_code));
  if v_sale is not null and v_sale > v_mrp then
    raise exception 'Selling price ₹% is more than the MRP ₹% — check the MRP decimals.', v_sale, v_mrp;
  end if;
  v_generic := exists (select 1 from generic_items g where g.label_prefix = v_prefix);

  -- 1) an existing product for this item + size
  select o.id into v_pid
  from barcode_options o
  left join generic_aliases ga on ga.alias_prefix = o.product
  left join brand_aliases ba on ba.alias = split_part(o.product, ' ', 1)
  where o.size = v_size
    and coalesce(ga.label_prefix,
                 case when ba.alias is not null then ba.brand || substr(o.product, length(ba.alias) + 1)
                      else o.product end) = v_prefix
    and (not v_generic or o.price_code = v_code or o.price_code is null)
  order by (o.price_code is distinct from v_code), o.id desc
  limit 1;

  -- 2) none → new product with a new barcode
  --    (a product with exactly this name but no barcode yet just gets the barcode)
  if v_pid is null then
    v_name := v_prefix || ' ' || v_size || ' ' || v_code;
    select id into v_pid from products where lower(name) = lower(v_name) and item_code is null;
    if v_pid is not null then
      update products set item_code = new_barcode() where id = v_pid;
    else
      if exists (select 1 from products where lower(name) = lower(v_name)) then
        raise exception 'A product named "%" already exists but the wizard can''t read it — check its item code.', v_name;
      end if;
      insert into products (name, item_code, category, mrp, sale_price, purchase_price, online_price, base_unit)
      values (v_name, new_barcode(),
              coalesce((select g.category from generic_items g where g.label_prefix = v_prefix),
                       case when exists (select 1 from innerwear_brands b where v_prefix like b.brand || '%') then 'Innerwear' end),
              v_mrp, coalesce(v_sale, 0), coalesce(v_cost, 0), coalesce(v_sale, 0), 'PIECES')
      returning id into v_pid;
    end if;
    v_created := true;
  end if;

  -- selling price follows the price code; MRP is just the latest one printed
  update products set
    sale_price     = case when v_sale is not null and v_sale > 0 then v_sale else sale_price end,
    online_price   = case when v_sale is not null and v_sale > 0 and online_price = sale_price then v_sale else online_price end,
    purchase_price = case when v_cost is not null and v_cost >= 0 then v_cost else purchase_price end,
    mrp            = v_mrp,
    updated_at     = now()
  where id = v_pid;

  select id, name, item_code, sale_price, purchase_price, stock, mrp into pr from products where id = v_pid;
  return jsonb_build_object(
    'barcode_number', pr.item_code, 'item_name', pr.name, 'created', v_created,
    'mrp', v_mrp, 'code', v_code,
    'product', jsonb_build_object('id', pr.id, 'name', pr.name, 'item_code', pr.item_code,
                                  'sale_price', pr.sale_price, 'purchase_price', pr.purchase_price,
                                  'stock', pr.stock, 'mrp', pr.mrp));
end $$;

-- Label details for products (for printing labels of scanned items).
create or replace function public.label_info(p_product_ids bigint[]) returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_manager() then raise exception 'Not allowed'; end if;
  return coalesce((select jsonb_object_agg(p.id, jsonb_build_object(
      'item_name', p.name, 'barcode', p.item_code, 'mrp', p.mrp))
    from products p where p.id = any(p_product_ids)), '{}'::jsonb);
end $$;

