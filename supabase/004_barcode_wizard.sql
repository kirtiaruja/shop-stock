-- ---------- views over products (same reading rules as the old tool) ------------
create or replace view public.barcode_options as
  with base as (
    select p.id, p.name as item_name, p.item_code as barcode_number,
           upper(regexp_replace(trim(p.name), '\s+', ' ', 'g')) as nm
    from public.products p
    where p.item_code is not null
  ), coded as (
    select base.*,
           substring(nm, '.*(?:^| |-)([A-KZ][0-9]{2,3})(?:[-/][0-9])?(?=$| |-)') as price_code,
           regexp_replace(regexp_replace(nm, '^(.*)(?:^| |-)[A-KZ][0-9]{2,3}(?:[-/][0-9])?(?=$| |-)', '\1 '), '[ -]+$', '') as rest
    from base
  ), sized as (
    select coded.*,
           replace(substring(rest, '(?:^| |-)([0-9]?X{0,4}L|XS|S|M|[0-9]{2,3} ?CM|[0-9]{2,3})$'), ' ', '') as size,
           trim(regexp_replace(regexp_replace(rest, '(?:^| |-)([0-9]?X{0,4}L|XS|S|M|[0-9]{2,3} ?CM|[0-9]{2,3})$', ''), '[ -]+$', '')) as product
    from coded
  )
  select s.id, s.item_name, s.barcode_number, s.product, s.size, s.price_code, pc.price,
         coalesce(r.category,
                  case when s.size ~ '^[0-9]{2,3}$' and s.size::int between 60 and 120 then 'Innerwear' end,
                  'Other') as category
  from sized s
  left join public.price_codes pc on pc.code = s.price_code
  left join lateral (
    select cr.category from public.category_rules cr
    where s.nm ~ cr.pattern order by cr.priority, cr.id limit 1
  ) r on true;

create or replace view public.generic_options as
  select o.id, o.item_name, o.barcode_number, o.size, o.price_code,
         g.category, g.style, g.sleeve, g.label_prefix
  from public.barcode_options o
  left join public.generic_aliases ga on ga.alias_prefix = o.product
  join public.generic_items g on g.label_prefix = coalesce(ga.label_prefix, o.product);

create or replace view public.innerwear_options as
  select o.id, o.item_name, o.barcode_number, o.size, o.price_code, ib.brand,
         nullif(trim(substr(o.product, length(split_part(o.product, ' ', 1)) + 1)), '') as style,
         case when o.product ~ '\mCOL\M' then 'Colour' when o.product ~ '\mWH\M' then 'White' end as colour
  from public.barcode_options o
  join public.innerwear_brands ib on ib.brand = coalesce(
         (select a.brand from public.brand_aliases a where a.alias = split_part(o.product, ' ', 1)),
         split_part(o.product, ' ', 1))
  where not exists (select 1 from public.generic_options g where g.id = o.id)
    and o.product !~ 'SANDOW|SEDOW|SENDOW|SNEDOW';

