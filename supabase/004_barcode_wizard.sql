-- StockPilot – 004: Barcode Wizard (works directly on your products)
-- Run AFTER 001–003. Safe to run again. Then run 005_barcode_cleanup.sql once.
--
-- The wizard reads your PRODUCTS: product name = label name ("JEANS 32 A300"),
-- item code = barcode. A new barcode is simply a new product.
-- Only the wizard's menu lives in its own small tables:
--   generic_items / generic_aliases   Category › Style › Sleeve → label prefix
--   innerwear_brands / brand_aliases  innerwear brands (+ misspellings)
--   category_rules / price_codes      used to read older product names
--   product_barcodes                  extra barcode numbers of a product (old labels)
-- Keep wizard-made product names in the label format, or the wizard won't recognise them.
-- =====================================================================

-- ---------- wizard menu tables ----------------------------------------------
create table if not exists public.generic_items (
  id            integer generated by default as identity primary key,
  category      text not null,
  style         text not null,
  sleeve        text,
  label_prefix  text not null unique,
  sort_order    integer default 100
);
create table if not exists public.generic_aliases (
  alias_prefix  text primary key,
  label_prefix  text not null references public.generic_items (label_prefix) on update cascade
);
create table if not exists public.innerwear_brands (
  brand       text primary key,
  sort_order  integer default 100
);
create table if not exists public.brand_aliases (
  alias  text primary key,
  brand  text not null
);
create table if not exists public.category_rules (
  id        integer generated by default as identity primary key,
  category  text not null,
  pattern   text not null,
  priority  integer not null default 100
);
create table if not exists public.price_codes (
  code   text primary key,
  price  numeric
);

